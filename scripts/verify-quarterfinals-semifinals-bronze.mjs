// Simulation: is Tournament Mode ready to take a 2-pool Round Robin event
// (5 teams / 4 teams, the real shape of the currently-open "Mixed beginner
// novice moneyball tournament") all the way through Quarterfinals ->
// Semifinals -> Championship Match, WITH a Bronze Medal Match (3rd place)?
//
// Pure simulation against an in-memory storage shim — touches no real
// session, no production data. Mirrors the real tournament's shape:
// doubles, 2 pools, poolCount sizes [5, 4] (distributeEvenly(9, 2)),
// advancesPerPool 4 (the maximum the smaller pool of 4 allows) so exactly
// 8 teams qualify — the only qualifier count that's both a power of two
// (bracket-generatable) AND reachable from these two pool sizes.
//
// Usage: node scripts/verify-quarterfinals-semifinals-bronze.mjs
const store = new Map();
globalThis.window = { storage: {
  get: async (k) => (store.has(k) ? { value: store.get(k) } : null),
  set: async (k, v) => { store.set(k, v); return { value: v }; },
  delete: async (k) => { store.delete(k); return {}; },
  list: async () => ({ keys: [...store.keys()] }),
} };

const T = await import("../src/lib/tournament.js");
const { collectMatches } = await import("../src/engines/CourtAssignmentService.js");

let pass = 0, fail = 0;
function assert(desc, cond) { if (cond) { pass++; console.log(`  ok ${desc}`); } else { fail++; console.log(`  FAIL: ${desc}`); } }

const mkPlayer = (id, name) => ({ id, name, checkedIn: true, status: "ACTIVE" });
// 18 players -> 9 doubles teams -> distributeEvenly(9, 2) = [5, 4], exactly
// the real tournament's Pool A (5) / Pool B (4).
const players = Array.from({ length: 18 }, (_, i) => mkPlayer(`p${i}`, `Player ${i}`));

console.log("\n1. Generate the Round Robin schedule (2 pools, doubles) — same shape as the real tournament");
let t = await T.buildAndSaveRoundRobinTournament({
  sessionCode: "SIMQFSFB1",
  players,
  mode: "doubles",
  courtsCount: 3,
  poolCount: 2,
  advancesPerPool: 4,
});
assert("2 pools created", t.pools.length === 2);
const sizes = t.pools.map((p) => p.entrants.length).sort((a, b) => b - a);
assert("pool sizes are [5, 4], matching the real tournament", sizes.join(",") === "5,4");
assert("advancesPerPool is 4 (top 4 of each pool -> 8 qualifiers, a power of two)", t.advancesPerPool === 4);

console.log("\n2. Enable the Bronze Medal Match (organizer Settings toggle) before playoffs start");
t = await T.saveTournamentSettings(t, { bronzeMatchEnabled: true });
assert("bronzeMatchEnabled is on", t.bronzeMatchEnabled === true);

console.log("\n3. Play every pool match to completion (deterministic: earlier-seeded team always wins)");
{
  let guard = 0;
  while (t.pools.some((p) => p.status !== "completed")) {
    if (++guard > 200) throw new Error("pool play didn't converge — possible infinite loop");
    const entry = collectMatches(t).find((e) => e.source === "pool" && e.match.status === "pending" && !e.match.isBye && e.match.teamA && e.match.teamB);
    if (!entry) break;
    const { match } = entry;
    // Deterministic, decisive result: whichever entrant sorts first wins 11-5.
    const aFirst = match.teamA.id < match.teamB.id;
    const result = aFirst ? { scoreA: 11, scoreB: 5, winnerId: match.teamA.id } : { scoreA: 5, scoreB: 11, winnerId: match.teamB.id };
    t = await T.saveMatchResult(t, match.id, result);
  }
  assert("both pools completed", t.pools.every((p) => p.status === "completed"));
  assert("no pool match left pending", collectMatches(t).filter((e) => e.source === "pool").every((e) => e.match.isBye || e.match.status === "completed"));
}

console.log("\n4. Bracket auto-generation (Standard Cross-Pool seeding auto-generates on pool completion)");
{
  const autoGenerated = Boolean(t.bracket);
  if (!autoGenerated) {
    // Fell back to the explicit action if auto-generation didn't fire for
    // any reason (e.g. seedingMethod isn't the default) — still a valid,
    // organizer-available path, not a failure of "is the app ready".
    t = await T.saveGenerateBracket(t);
  }
  assert(`bracket exists (${autoGenerated ? "auto-generated on last pool match" : "via explicit Generate Bracket"})`, Boolean(t.bracket));
  assert("exactly 8 teams qualified into the bracket", t.bracket.rounds[0].matches.flatMap((m) => [m.teamA, m.teamB]).filter(Boolean).length === 8);
  assert("3 playoff rounds (QF, SF, Final)", t.bracket.rounds.length === 3);
  assert("round 1 is named Quarterfinals (4 matches)", t.bracket.rounds[0].name === "Quarterfinals" && t.bracket.rounds[0].matches.length === 4);
  assert("round 2 is named Semifinals (2 matches)", t.bracket.rounds[1].name === "Semifinals" && t.bracket.rounds[1].matches.length === 2);
  assert("round 3 is named Championship Match (1 match, the Final)", t.bracket.rounds[2].name === "Championship Match" && t.bracket.rounds[2].matches.length === 1);
  assert("the Bronze Medal Match (3rd place) exists and is empty until the semifinals finish", Boolean(t.bracket.bronzeMatch) && !t.bracket.bronzeMatch.teamA && !t.bracket.bronzeMatch.teamB);
  assert("every Quarterfinal already has both teams seeded (no TBD)", t.bracket.rounds[0].matches.every((m) => m.teamA && m.teamB));
  assert("Semifinals and the Final start empty (TBD until earlier rounds finish)", t.bracket.rounds[1].matches.every((m) => !m.teamA && !m.teamB) && !t.bracket.rounds[2].matches[0].teamA);
}

console.log("\n5. Play the Quarterfinals — Semifinals should populate with the 4 winners");
{
  for (const m of t.bracket.rounds[0].matches) {
    const aFirst = m.teamA.participantId < m.teamB.participantId;
    const result = aFirst ? { scoreA: 11, scoreB: 5, winnerId: m.teamA.participantId } : { scoreA: 5, scoreB: 11, winnerId: m.teamB.participantId };
    t = await T.savePlayoffMatchResult(t, m.id, result);
  }
  assert("Quarterfinals round is completed", t.bracket.rounds[0].status === "completed");
  assert("Semifinals are now fully seeded (4 QF winners advanced)", t.bracket.rounds[1].matches.every((m) => m.teamA && m.teamB));
  assert("the Final is still TBD (semifinals not played yet)", !t.bracket.rounds[2].matches[0].teamA);
  assert("the Bronze Match is still empty (semifinals not played yet)", !t.bracket.bronzeMatch.teamA && !t.bracket.bronzeMatch.teamB);
}

console.log("\n6. Play the Semifinals — the Final gets the 2 winners, the Bronze Match gets the 2 losers");
{
  const sfMatches = t.bracket.rounds[1].matches;
  const losers = [];
  for (const m of sfMatches) {
    const aFirst = m.teamA.participantId < m.teamB.participantId;
    const winnerId = aFirst ? m.teamA.participantId : m.teamB.participantId;
    const loserSide = aFirst ? m.teamB : m.teamA;
    losers.push(loserSide.participantId);
    const result = aFirst ? { scoreA: 11, scoreB: 5, winnerId } : { scoreA: 5, scoreB: 11, winnerId };
    t = await T.savePlayoffMatchResult(t, m.id, result);
  }
  assert("Semifinals completed", t.bracket.rounds[1].status === "completed");
  assert("the Final is now seeded with the 2 semifinal winners", Boolean(t.bracket.rounds[2].matches[0].teamA) && Boolean(t.bracket.rounds[2].matches[0].teamB));
  assert("the Bronze Match auto-populated with the 2 semifinal LOSERS (no organizer action needed)", Boolean(t.bracket.bronzeMatch.teamA) && Boolean(t.bracket.bronzeMatch.teamB));
  const bronzeIds = [t.bracket.bronzeMatch.teamA.participantId, t.bracket.bronzeMatch.teamB.participantId].sort();
  assert("the Bronze Match's two teams are EXACTLY the two semifinal losers, nobody else", JSON.stringify(bronzeIds) === JSON.stringify(losers.sort()));
}

console.log("\n7. Play the Bronze Medal Match and the Final — the tournament should fully complete");
{
  const bm = t.bracket.bronzeMatch;
  const bAFirst = bm.teamA.participantId < bm.teamB.participantId;
  t = await T.savePlayoffMatchResult(t, bm.id, bAFirst ? { scoreA: 11, scoreB: 8, winnerId: bm.teamA.participantId } : { scoreA: 8, scoreB: 11, winnerId: bm.teamB.participantId });
  assert("Bronze Match completed on its own, independent of the Final", t.bracket.bronzeMatch.status === "completed");
  assert("bracket isn't 'completed' yet — the Final hasn't been played", t.bracket.status !== "completed");

  const fm = t.bracket.rounds[2].matches[0];
  const fAFirst = fm.teamA.participantId < fm.teamB.participantId;
  t = await T.savePlayoffMatchResult(t, fm.id, fAFirst ? { scoreA: 11, scoreB: 9, winnerId: fm.teamA.participantId } : { scoreA: 9, scoreB: 11, winnerId: fm.teamB.participantId });

  assert("bracket is now completed", t.bracket.status === "completed");
  assert("a champion is set", Boolean(t.bracket.champion));
  assert("a runner-up is set", Boolean(t.bracket.runnerUp));
  assert("a 3rd place (thirdPlace) is set from the Bronze Match winner", Boolean(t.bracket.thirdPlace));
  assert("champion, runner-up, and 3rd place are three DIFFERENT teams", new Set([t.bracket.champion.participantId, t.bracket.runnerUp.participantId, t.bracket.thirdPlace.participantId]).size === 3);
  assert("tournament status reflects a completed event", t.status === "completed" || t.bracket.status === "completed");
}

console.log("\n8. Sanity: exactly the right number of playoff matches were ever created — 4 QF + 2 SF + 1 Final + 1 Bronze = 8");
{
  const playoffMatches = t.bracket.rounds.flatMap((r) => r.matches).length + 1; // +1 bronze
  assert("8 total playoff matches (QF x4, SF x2, Final x1, Bronze x1)", playoffMatches === 8);
  assert("every one of them is completed", t.bracket.rounds.every((r) => r.matches.every((m) => m.status === "completed")) && t.bracket.bronzeMatch.status === "completed");
}

console.log(`\n${pass} passed, ${fail} failed`);
if (fail > 0) process.exit(1);
